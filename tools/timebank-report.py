def write_slide_page(domain: str, title: str, sl: dict, deck: str, write: bool) -> str:
    slug = fedwiki.as_slug(title)
    path = fedwiki.page_path(domain, slug, FARM)
    page = load_or_none(domain, slug)
    if page:
        changed = False
        svg = find_item(page, lambda i: i.get("type") == "svg")
        if svg:
            changed |= set_item_text(page, svg, sl["svg"], DECK_PROV)
        story = page["story"]
        at = next((k for k, i in enumerate(story) if (fedwiki.heading_of(i) or "").lower() == "notes"), None)
        if at is not None and at + 1 < len(story) and story[at + 1].get("type") == "markdown":
            changed |= set_item_text(page, story[at + 1], sl["notes"], DECK_PROV)
        if changed and write:
            fedwiki.save_page(path, page)
        return "redrawn" if changed else "unchanged"
    page = fedwiki.make_page(title, [
        {"type": "svg", "text": sl["svg"]},
        "# Notes\n> Speaker notes: the figures on the slide, as prose.",
        sl["notes"],
        f"# See\n> The deck this slide belongs to.",
        f"- [[{deck}]] — the week's deck, which presents this slide\n- [[Review Board]] — the same slide, drawn in the page",
    ], provenance=DECK_PROV)
    if write:
        fedwiki.save_page(path, page)
    return "created"


def write_manifest(domain: str, week: str, text: str, masked: bool, write: bool) -> str:
    title = rd.deck_title(week)
    slug = fedwiki.as_slug(title)
    path = fedwiki.page_path(domain, slug, FARM)
    page = load_or_none(domain, slug)
    if page:
        item = find_item(page, lambda i: i.get("type") in ("code", "markdown") and re.match(r"^DECK\b", i.get("text") or ""))
        if not item:
            return "no DECK item (left alone)"
        changed = set_item_text(page, item, text, DECK_PROV)
        if changed and write:
            fedwiki.save_page(path, page)
        return "manifest updated" if changed else "manifest unchanged"
    mon, sun = tr.week_bounds(week)
    lead = (f"The **Review Deck** for ISO week {week}, {human_day(mon)} to {human_day(sun)}: the [[Review Board]]'s slides, one wiki page each, compiled by [[Wiki Deck]] into a deck the stage below presents. "
            + ("Press ⤢ Present for full screen, or add ?print-pdf to the deck's address for a PDF." if masked else
               "Press ⤢ Present for full screen. The broker signs in as presenter and everyone else who opens this page follows the slides over the [[Live Deck]] relay; add ?follow=0 to browse on your own, or ?print-pdf to the deck's address for a PDF."))
    page = fedwiki.make_page(title, [
        lead,
        fedwiki.make_item(text, type="code"),
        "The code item above is the Deck Manifest: DECK names the deck, THEME the [[Review Deck Theme]], TITLE HIDE keeps the page titles off slides that draw their own, WIDTH and HEIGHT fix the 1280 by 720 frame, LIVE the relay and PRESENTERS the logins that may drive it besides the site's owner. Each SLIDE line is one page. The report tool rewrites them when it redraws the week; `wiki-deck install` recompiles the deck into this page's assets.",
        "# See\n\n- [[Review Board]] — the board these slides come from\n- [[Weekly Review]] — the meeting the deck is for\n- [[Review Meeting Plan]] — why the board became a deck",
    ], provenance=DECK_PROV)
    if write:
        fedwiki.save_page(path, page)
        seed_neighbours(domain, slug, NEIGHBOURS_EXTRA)
    return "created"


def write_deck(a, domain: str, broker_site: str, members: list[dict], weeks: dict, stamp: str, write: bool) -> None:
    week = a.deck.upper()
    masks = rd.load_masks(a.masks) if a.masks is not None else None
    board = load_or_none(domain, "review-board")
    models = [i["text"] for i in (board or {}).get("story", []) if i.get("type") == "model"]
    ledger = {"week": week, "rows": rd.ledger_rows(tr.summarise(weeks.get(week, []), members))}
    root, _ = fedwiki.resolve_root(domain, FARM)
    slugs = sorted(os.listdir(os.path.join(str(root), "pages"))) if os.path.isdir(os.path.join(str(root), "pages")) else []
    prev = rd.previous_meeting(slugs, week)
    lines = rd.meeting_lines(load_or_none(domain, prev)) if prev else {"attendance": [], "mood": []}
    meta = {"week": week, "site": None if masks else broker_site, "broker": a.broker, "generated": dt.date.today().strftime("%-d %B %Y"),
            "page": rd.deck_title(week), "attendance": lines["attendance"], "mood": lines["mood"], "masks": masks}
    slides = rd.render(models, ledger, meta)
    titles = [rd.slide_title(week, n, sl["key"]) for n, sl in enumerate(slides, 1)]
    print(f"  Review Deck {week}: {len(slides)} slides" + (f"; attendance and mood from {prev}" if prev else "; no earlier Review Meeting page") +
          ("; names masked" if masks else ""))
    for t, sl in zip(titles, slides):
        print(f"    {t}: {write_slide_page(domain, t, sl, rd.deck_title(week), write)}")
    text = rd.manifest_text(week, titles, presenters=None if masks else (a.presenters or None), relay=None if masks else rd.RELAY)
    print(f"    {rd.deck_title(week)}: {write_manifest(domain, week, text, bool(masks), write)}")
    print(f"    {rd.THEME_TITLE}: {ensure_theme(domain, write)}")
    print(f"    compile: node ~/Code/wiki-deck/bin/wiki-deck.js install {'http' if domain.endswith('localhost') else 'https'}://{domain}/{fedwiki.as_slug(rd.deck_title(week))}.json"
          + (f" --farm {FARM}" if FARM else ""))


# --- main ---------------------------------------------------------------------

def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--known", default="http://david.localhost:4242/view/known-ledgers", help="the Known Ledgers page")
    ap.add_argument("--broker", default="David Bovill")
    ap.add_argument("--dry-run", action="store_true", help="compute and print; write nothing")
    ap.add_argument("--json", action="store_true", help="print the computed figures as JSON")
    ap.add_argument("--freeze", default=os.path.join(HERE, "..", "..", "wiki-plugin-model", "scripts", "freeze.js"),
                    help="wiki-model-freeze (wiki-plugin-model scripts/freeze.js)")
    ap.add_argument("--review-model", action="store_true", help="write the Review Model workbook and refreeze the pages that read it")
    ap.add_argument("--plan", nargs=4, action="append", metavar=("WEEK", "MEMBER", "HOURS", "TASKS"),
                    help="set one Plan row of the Review Model (implies --review-model)")
    ap.add_argument("--approve", metavar="WEEK", help="approve one week, once only (implies --review-model)")
    ap.add_argument("--approver", help="who approved (default: --broker)")
    ap.add_argument("--workbook-only", action="store_true",
                    help="write the workbook and stop: no page is written or refrozen (a sheet edit the badges should notice)")
    ap.add_argument("--approved-on", help="the approval date, YYYY-MM-DD (default: today)")
    ap.add_argument("--out", metavar="DIR",
                    help="write the broker's pages and assets under DIR/<broker domain>/ instead of the farm — for a broker site on "
                         "another machine (the Pi5's tailnet sites): rsync it from there first, run, rsync it back")
    ap.add_argument("--deck", metavar="WEEK",
                    help="write the Review Deck for WEEK: one page per slide, the manifest, the theme (implies --review-model)")
    ap.add_argument("--masks", nargs="?", const="default", metavar="MAP",
                    help="with --deck: draw the fish masks instead of names, for public output — a JSON file "
                         f"(default {rd.MASKS_FILE}) or Name=Fish,…; drops LIVE, PRESENTERS and the site name")
    ap.add_argument("--presenters", nargs="*", default=["david"],
                    help="relay logins for the manifest's PRESENTERS line (Keycloak usernames; the site owner presents anyway)")
    a = ap.parse_args()
    global FARM
    FARM = os.path.abspath(os.path.expanduser(a.out)) if a.out else None
    a.review_model = a.review_model or bool(a.plan) or bool(a.approve) or bool(a.deck)

    broker_site, _, members = known_ledgers(a.known)
    domain = re.sub(r":\d+$", "", broker_site)
    ledgers, sites = read_ledgers(members)
    copies = gather(sites)
    ts = [t for t in tr.dedupe(copies) if t["facts"]["valid"] and
          (tr.member_of(t["facts"]["giver"], members) or tr.member_of(t["facts"]["receiver"], members))]
    for t in ts:
        t["state"] = tr.state_of(t, ledgers)
    weeks = tr.by_week(ts)
    months = tr.by_month(ts)
    stamp = dt.datetime.now(dt.timezone.utc).strftime("%-d %B %Y at %H:%M UTC")
    unpaged = unpaged_lines(ledgers)

    print(f"members {[m['member'] for m in members]}; sites read {sites}; {len(copies)} copies -> {len(ts)} transactions")
    for l in ledgers:
        print(f"  {l['member']}: {'reachable' if l['reachable'] else 'UNREACHABLE'}, {len(l['entries'])} linked entries in "
              f"{len(l['periods']) or 1} {'period ledgers' if l['periods'] else 'ledger'}, watch {l['watch']}")
    for month, mts in months.items():
        s = tr.summarise(mts, members)
        print(f"  {month}: {s['count']} transactions, {tr.fmt_hours(s['total'])} given — " +
              ", ".join(f"{r['member']} +{tr.fmt_hours(r['given'])}/-{tr.fmt_hours(r['received'])}" for r in s["rows"]) + f" — {state_counts(mts)}")
    for week, wts in weeks.items():
        s = tr.summarise(wts, members)
        print(f"  {week}: {s['count']} transactions, {tr.fmt_hours(s['total'])} given — " +
              ", ".join(f"{r['member']} +{tr.fmt_hours(r['given'])}/-{tr.fmt_hours(r['received'])}" for r in s["rows"]) + f" — {state_counts(wts)}")
    if a.json:
        print(json.dumps({"months": {m: tr.summarise(x, members) for m, x in months.items()},
                          "weeks": {w: tr.summarise(x, members) for w, x in weeks.items()}, "total": tr.summarise(ts, members),
                          "transactions": [{"home": t["home"], "slug": t["facts"]["page"]["slug"], "state": t["state"], "forks": t["forks"]} for t in ts]}, indent=1))
    check = tr.ledger_check(ledgers, tr.summarise(ts, members))
    print("  ledger check — summary ledger net (logged) against report net:")
    for c in check:
        print(f"    {c['member']}: ledger {num(c['ledger'])}h, report {num(c['report'])}h, difference {num(c['diff'])}h over {c['periods']} period ledgers")
    write = not a.dry_run
    frozen = review_model_step(a, domain, broker_site, members, ts) if a.review_model else None
    if a.workbook_only:
        print("  --workbook-only: no page written; the model items' badges will read Update available where their figures moved")
        return
    for month, mts in months.items():
        title, _, ch = write_monthly(domain, month, mts, members, a.broker, stamp, write)
        print(f"  {'wrote' if write else 'would write'} http://{broker_site}/view/{fedwiki.as_slug(title)}: {', '.join(ch) or 'unchanged'}")
        if write:
            seed_neighbours(domain, fedwiki.as_slug(title), [m["site"] for m in members if not tr.same_site(m["site"], broker_site)] + NEIGHBOURS_EXTRA)
    for week, wts in weeks.items():
        title, _, ch = write_weekly(domain, week, wts, members, a.broker, stamp, write, frozen)
        print(f"  {'wrote' if write else 'would write'} http://{broker_site}/view/{fedwiki.as_slug(title)}: {', '.join(ch) or 'unchanged'}")
        if write:
            seed_neighbours(domain, fedwiki.as_slug(title), [m["site"] for m in members if not tr.same_site(m["site"], broker_site)] + NEIGHBOURS_EXTRA)
    total, ch = write_total(domain, weeks, ts, members, a.broker, stamp, unpaged, write, months=months, check=check)
    print(f"  {'wrote' if write else 'would write'} http://{broker_site}/view/timebank-report: {', '.join(ch) or 'unchanged'}")
    if write:
        seed_neighbours(domain, "timebank-report", [m["site"] for m in members if not tr.same_site(m["site"], broker_site)] + NEIGHBOURS_EXTRA)
        if frozen:
            write_review_pages(domain, frozen, write)
            lw = (a.deck or frozen["layout"]["weeks"][-1]).upper() if (a.deck or frozen["layout"]["weeks"]) else None
            if lw:
                print("  Review Board: " + ledger_on_board(domain, lw, rd.ledger_rows(tr.summarise(weeks.get(lw, []), members)), write))

        else:
            root, _ = fedwiki.resolve_root(domain, FARM)
            xlsx = os.path.join(str(root), "assets", "timebank-report", "equity-model.xlsx")
            equity_workbook(xlsx, total, ts, members)
            print(f"  wrote {xlsx}")
            print("  " + ensure_model_item(domain, xlsx, len(members), a.freeze))
    if a.deck:
        write_deck(a, domain, broker_site, members, weeks, stamp, write)


if __name__ == "__main__":
    main()
