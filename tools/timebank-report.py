def review_model_step(a, domain: str, broker_site: str, members: list[dict], ts: list[dict]) -> dict:
    """Write the workbook; return the frozen texts the pages need."""
    root, _ = fedwiki.resolve_root(domain, FARM)
    xlsx = os.path.join(str(root), "assets", "review-model", "review-model.xlsx")
    names = [m["member"] for m in members]
    info = [{"member": m["member"], "site": m["site"], "url": page_url(m["site"], m["slug"])} for m in members]
    state = rm.alias_state(rm.load_state(xlsx), names)
    for week, rows in rm.DEFAULT_PLAN.items():
        if week not in state["plan"]:
            state["plan"][week] = {rm.member_alias(k, names): v for k, v in rows.items() if rm.member_alias(k, names) in names}
    for week, member, hours, tasks in a.plan or []:
        member = rm.member_alias(member, names)
        state["plan"].setdefault(week.upper(), {})[member] = (float(hours), tasks)
        print(f"  plan {week} {member}: {hours} hours — {tasks}")
    txs = review_txs(ts, members)
    totals = rm.weekly_totals(txs, names)
    done = {x["week"] for x in state["approved"]}
    approvals = {}
    # approvals made on the report pages (the REVIEW item's Approve button) that the workbook has not burned yet
    for week in sorted(state["plan"]):
        page = load_or_none(domain, fedwiki.as_slug(weekly_title(week)))
        it = review_item(page, week)
        r = rm.parse_review(it["text"]) if it else None
        if r and r["approved"]:
            approvals[week] = it["text"]
            if week not in done:
                hours = [(rm.member_alias(m, names), h) for m, h in r["hours"]]
                state["approved"] += rm.approve_rows(week, r["approved"]["on"], r["approved"]["by"], hours, totals)
                done.add(week)
                print(f"  burned {week}: approved on the report page on {r['approved']['on']} by {r['approved']['by']}")
    if a.approve:
        week = a.approve.upper()
        if week not in state["plan"]:
            sys.exit(f"--approve {week}: no plan for {week} in the Review Model, so nothing to review")
        if week in done:
            first = next(x for x in state["approved"] if x["week"] == week)
            sys.exit(f"--approve {week}: already approved on {first['on']} by {first['approver']} — a week is burned once only")
        on = a.approved_on or dt.date.today().isoformat()
        hours = [(m, totals.get((week, m), {}).get("given", 0.0)) for m in names]
        state["approved"] += rm.approve_rows(week, on, a.approver or a.broker, hours, totals)
        approvals[week] = rm.approval_text(week, on, a.approver or a.broker, hours)
        print(f"  approved {week} on {on} by {a.approver or a.broker}: " + ", ".join(f"{m} {h:g}h" for m, h in hours))
    sheets, dnames, layout, figures = rm.build(info, txs, state)
    if not a.dry_run:
        rm.write_xlsx(xlsx, sheets, dnames)
        print(f"  wrote {xlsx}: tabs {', '.join(n for n, _ in sheets)}; shares {layout['shares']}; weeks {', '.join(layout['weeks'])}")
    else:
        print(f"  would write {xlsx}")
    tmp = xlsx if not a.dry_run else None
    frozen = {"plan": {}, "review": {}, "approvals": approvals, "figures": figures, "layout": layout, "xlsx": xlsx, "txs": txs, "totals": totals}
    if tmp:
        for week in layout["weeks"]:
            plan_page = load_or_none(domain, fedwiki.as_slug(weekly_plan_title(week)))
            ex = model_with_caption(plan_page, plan_caption(week))
            frozen["plan"][week] = freeze(a.freeze, xlsx, "Plan", layout["plan"][week], plan_caption(week),
                                          "Member, Estimated hours, Tasks", ex and ex["text"])
            rep = load_or_none(domain, fedwiki.as_slug(weekly_title(week)))
            ex = model_with_caption(rep, review_caption(week))
            frozen["review"][week] = freeze(a.freeze, xlsx, "Review", layout["review"][week], review_caption(week),
                                            "Member, Planned, Actual, Variance, Approved, Approved on, Approver", ex and ex["text"])
        total = load_or_none(domain, "timebank-report")
        ex = model_with_caption(total, SHARES_CAPTION)
        frozen["shares"] = freeze(a.freeze, xlsx, "Equity", layout["shares"], SHARES_CAPTION, existing=ex and ex["text"])
        board = load_or_none(domain, "review-board")
        ex = model_with_caption(board, BOARD_REVIEW_CAPTION)
        frozen["review_all"] = freeze(a.freeze, xlsx, "Review", layout["review_all"], BOARD_REVIEW_CAPTION, existing=ex and ex["text"])
    return frozen


