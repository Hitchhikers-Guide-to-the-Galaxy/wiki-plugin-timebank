def get_json(url: str):
    """GET json. *.localhost names do not resolve through the system resolver
    (curl and browsers special-case them), so they go to 127.0.0.1 with a Host header."""
    req = urllib.request.Request(url)
    m = re.match(r"^(https?)://([^/:]+\.localhost)(:\d+)?(/.*)$", url)
    if m:
        req = urllib.request.Request(f"{m.group(1)}://127.0.0.1{m.group(3) or ''}{m.group(4)}",
                                     headers={"Host": m.group(2) + (m.group(3) or "")})
    try:
        with urllib.request.urlopen(req, timeout=10) as r:
            return json.loads(r.read().decode("utf-8"))
    except (urllib.error.URLError, TimeoutError, ValueError):
        return None


def scheme_for(site: str) -> str:
    return "http" if re.search(r":\d+$", site) or re.search(r"(^|\.)localhost$", site) or site.endswith(".local") else "https"


def page_url(site: str, slug: str) -> str:
    return f"{scheme_for(site)}://{site}/view/{slug}"


def fetch_page(site: str, slug: str):
    return get_json(f"{scheme_for(site)}://{site}/{slug}.json")


def table_rows(text: str) -> list[dict]:
    """Rows of a Table Plugin item written as a markdown table."""
    lines = [l.strip() for l in text.split("\n") if l.strip().startswith("|")]
    if len(lines) < 2:
        return []
    cells = lambda l: [c.strip() for c in re.split(r"(?<!\\)\|", l.strip().strip("|"))]  # noqa: E731
    head = cells(lines[0])
    return [dict(zip(head, cells(l))) for l in lines[2:]]


def known_ledgers(url: str) -> tuple[str, str, list[dict]]:
    m = re.match(r"^(https?)://([^/]+)/view/([a-z0-9-]+)", url)
    if not m:
        sys.exit(f"--known must be http://site/view/slug, not {url}")
    site, slug = m.group(2), m.group(3)
    page = fetch_page(site, slug)
    if not page:
        sys.exit(f"cannot read {url}")
    table = next((i for i in page["story"] if i.get("type") == "table"), None)
    if not table:
        sys.exit(f"{url} has no table item")
    members = []
    for r in table_rows(table["text"]):
        if r.get("Site") and r.get("Slug"):
            members.append({"member": r.get("Member") or r["Slug"], "site": tr.norm_site(r["Site"]), "slug": r["Slug"].strip()})
    return site, page.get("title", "Known Ledgers"), members


def period_pages(site: str, page: dict) -> list[tuple[dict, dict]]:
    """A summary ledger's period pages, read from its site: [(ref, page)]."""
    sitemap = get_json(f"{scheme_for(site)}://{site}/system/sitemap.json")
    out = []
    for ref in tr.period_pages_of(sitemap, page.get("title")):
        pg = fetch_page(site, ref["slug"])
        if pg:
            out.append((ref, pg))
    return out


def read_ledgers(members: list[dict]) -> tuple[list[dict], list[str]]:
    ledgers, sites = [], []
    add = lambda s: sites.append(tr.norm_site(s)) if s and not any(tr.same_site(s, x) for x in sites) else None  # noqa: E731
    for m in members:
        page = fetch_page(m["site"], m["slug"])
        pages = [page] if page else []
        periods = []
        if page and tr.is_summary(page):
            got = period_pages(m["site"], page)
            periods = [ref["title"] for ref, _ in got]
            pages += [pg for _, pg in got]
            ref = tr.extract_commands("\n".join(i.get("text", "") for i in page["story"] if i.get("type") == "timebank"))["owner"]
            about = None
            if ref and ref.get("slug") == tr.ABOUT_REF["slug"]:  # OWNER: [[About]] — read its Site Record
                about = fetch_page(ref["site"] if ref.get("external") else m["site"], ref["slug"])
            owner = tr.owner_name(ref, about)
            if owner:
                m["member"] = owner
        text = "\n".join(i.get("text", "") for pg in pages for i in pg.get("story", []) if i.get("type") == "timebank")
        entries = [e for pg in pages for e in tr.ledger_entries(pg, m["site"])]
        cmd = tr.extract_commands(text)
        ledgers.append({**m, "entries": entries, "reachable": bool(page), "lineup": cmd["lineup"], "watch": cmd["watch"], "text": text,
                        "periods": periods, "logged": tr.logged_balance(entries)})
        add(m["site"])
        for s in cmd["watch"]:
            add(s)
        for e in entries:
            if e["counterparty"].get("external"):
                add(e["counterparty"]["site"])
    return ledgers, sites


def gather(sites: list[str]) -> list[dict]:
    copies = []
    for site in sites:
        sitemap = get_json(f"{scheme_for(site)}://{site}/system/sitemap.json")
        for slug in tr.transaction_candidates(sitemap):
            page = fetch_page(site, slug)
            if not page:
                continue
            home = tr.home_site(page, site)
            for f in tr.page_transactions(page, site, slug):
                copies.append({"facts": f, "site": site, "home": home})
    return copies


def unpaged_lines(ledgers: list[dict]) -> list[str]:
    out = []
    for l in ledgers:
        for e in l["entries"]:
            if not e.get("txn"):
                cp = e["counterparty"]
                where = "" if cp.get("external") else " on its own site"
                out.append(f"{l['member']}: {e['label']} {'for' if e['direction'] == 'gave' else 'from'} {cp['name']}{where}, {tr.fmt_hours(e['time'])}")
    return out


