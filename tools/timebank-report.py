def write_weekly_plan(domain: str, week: str, text: str, write: bool) -> str:
    """Weekly Plan <week> from the Weekly Plan Template: its story cloned, the lead
    written for the week, the model item frozen. On a rerun only the model item
    is refreshed; the meeting's notes are theirs."""
    slug = fedwiki.as_slug(weekly_plan_title(week))
    path = fedwiki.page_path(domain, slug, FARM)
    if os.path.exists(path):
        page = fedwiki.load_page(path)
        item = model_with_caption(page, plan_caption(week)) or find_item(page, lambda i: i.get("type") == "model")
        if not item:
            return "no model item (left alone)"
        changed = set_item_text(page, item, text, REVIEW_PROV)
        if changed and write:
            fedwiki.save_page(path, page)
        return "refrozen" if changed else "unchanged"
    tpl = load_or_none(domain, "weekly-plan-template")
    if not tpl:
        return "no Weekly Plan Template on the site"
    mon, sun = tr.week_bounds(week)
    story = []
    for n, it in enumerate(tpl["story"]):
        t = (it.get("text") or "").strip()
        if n and it.get("type") == "markdown" and t.startswith("*") and t.endswith("*") and "\n" not in t:
            continue  # the template's placeholder guidance; the tool writes the real thing
        it = {k: v for k, v in it.items() if k != "id"}
        it["id"] = fedwiki.nid()
        story.append(it)
    story[0]["text"] = (f"The plan for ISO week {week}, {human_day(mon)} to {human_day(sun)}: each member's estimated hours and "
                        f"tasks, as the [[Planning Meeting]] wrote them in the Plan tab of the [[Review Model]]. The table is "
                        f"frozen from the workbook; its badge says whether the sheet has moved on. The week's report, "
                        f"[[{weekly_title(week)}]], sets these estimates against what was given.")
    item = find_item({"story": story}, lambda i: i.get("type") == "model")
    item["text"] = text
    page = fedwiki.make_page(weekly_plan_title(week), story, provenance=REVIEW_PROV + " Made from the [[Weekly Plan Template]].")
    if write:
        fedwiki.save_page(path, page)
        seed_neighbours(domain, slug, NEIGHBOURS_EXTRA)
    return "created from the template"


