def name_of(ref, members) -> str:
    m = tr.member_of(ref, members)
    return m["member"] if m else f"{ref.get('name')} ({ref.get('site')})"


def num(h: float) -> str:
    return f"{h:g}" if h == round(h, 2) else f"{h:.2f}"


def people_table(summary: dict, caption: str) -> dict:
    rows = [[r["member"], num(r["given"]), num(r["received"]), num(r["net"]), r["verified"], r["awaiting"]] for r in summary["rows"]]
    return fedwiki.make_table(["Member", "Given", "Received", "Net", "Verified", "Awaiting"], rows, caption=caption, layout="table")


def transactions_table(ts: list[dict], members: list[dict], caption: str) -> dict:
    rows = []
    for t in sorted(ts, key=lambda t: (t["facts"]["date"] or 0, t["facts"]["page"].get("title") or "")):
        f = t["facts"]
        title = f["page"].get("title") or f["page"]["slug"]
        link = f"[{page_url(t['home'], f['page']['slug'])} {title}]"
        date = dt.datetime.fromtimestamp(f["date"] / 1000, dt.timezone.utc).date().isoformat() if f["date"] else ""
        rows.append([link, date, name_of(f["giver"], members), name_of(f["receiver"], members), num(f["minutes"] / 60), t["state"]])
    return fedwiki.make_table(["Transaction", "Date", "Giver", "Receiver", "Hours", "State"], rows, caption=caption, layout="table")


def shares_table(summary: dict) -> dict:
    rows = [[r["member"], num(r["given"]), f"{100 * r['share']:.1f}%"] for r in summary["rows"]]
    return fedwiki.make_table(["Member", "Hours given", "Share"], rows, caption="Each member's share of all hours given", layout="table")


def svg_item(svg: str, caption: str) -> dict:
    """Inline source: the SVG plugin takes no caption in source mode, so the
    caption rides inside the drawing as its <title> (a tooltip)."""
    return {"type": "svg", "text": svg.replace(">", f"><title>{tr._esc(caption)}</title>", 1)}


def state_counts(ts) -> str:
    c = {}
    for t in ts:
        c[t["state"]] = c.get(t["state"], 0) + 1
    return ", ".join(f"{n} {s}" for s, n in sorted(c.items(), key=lambda x: ["verified", "in dialogue", "awaiting", "unknown party"].index(x[0])))


def seed_neighbours(domain: str, slug: str, sites: list[str]) -> None:
    path = fedwiki.page_path(domain, slug, FARM)
    page = fedwiki.load_page(path)
    lead = []
    for a in page.get("journal", []):
        if a.get("type") != "fork":
            break
        lead.append(a.get("site"))
    changed = False
    for s in sites:
        if s not in lead:
            fedwiki.seed_fork(page, s)
            lead.append(s)
            changed = True
    if changed:
        fedwiki.save_page(path, page)


