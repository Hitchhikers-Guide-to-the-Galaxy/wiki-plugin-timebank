REVISION_RE = re.compile(r"^REVISION\s+sha256:([0-9a-f]+)", re.M)


def review_txs(ts: list[dict], members: list[dict]) -> list[dict]:
    out = []
    for t in ts:
        f = t["facts"]
        date = dt.datetime.fromtimestamp(f["date"] / 1000, dt.timezone.utc).date().isoformat()
        explicit = re.search(r"\bCategory:\s*([A-Za-z]+)", f.get("note") or "")
        out.append({"date": date, "week": tr.iso_week(f["date"]), "title": f["page"].get("title") or f["page"]["slug"],
                    "giver": name_of(f["giver"], members), "receiver": name_of(f["receiver"], members),
                    "hours": f["minutes"] / 60, "category": rm.category_of(f.get("label"), explicit and explicit.group(1)),
                    "state": t["state"], "url": page_url(t["home"], f["page"]["slug"])})
    return out


def freeze(freeze_js: str, xlsx: str, sheet: str, rng: str, caption: str, columns: str | None = None,
           existing: str | None = None, layout: str = "table") -> str:
    """wiki-model-freeze's text for one range; the existing text when the figures
    (the REVISION hash of the shown values) have not moved, so a rerun is a no-op."""
    cmd = ["node", freeze_js, xlsx, "--source", MODEL_SRC, "--sheet", sheet, "--range", rng, "--caption", caption, "--layout", layout]
    if columns:
        cmd += ["--columns", columns]
    text = subprocess.run(cmd, capture_output=True, text=True, check=True).stdout.strip()
    if existing:
        old, new = REVISION_RE.search(existing), REVISION_RE.search(text)
        same_range = f"RANGE {rng}" in existing and f"SHEET {sheet}" in existing
        if old and new and old.group(1) == new.group(1) and same_range:
            return existing
    return text


def caption_of(text: str) -> str | None:
    m = re.search(r"^CAPTION\s+(.*)$", text or "", re.M)
    return m.group(1).strip() if m else None


